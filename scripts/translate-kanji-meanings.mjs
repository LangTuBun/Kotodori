let missing = []
for (const [char, entry] of Object.entries(data)) {
  const en = Array.isArray(entry.meanings) ? entry.meanings.join(", ") : entry.meanings?.en ?? ""
  const vi = viTranslations[char]
  if (vi === undefined) {
    missing.push(char)
    entry.meanings = { vi: en, en } // fall back to English rather than drop data
  } else {
    entry.meanings = { vi, en }
    translated++
  }
}

